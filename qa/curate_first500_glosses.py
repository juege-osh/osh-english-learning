lines = [line for line in curated.strip().splitlines() if line]
assert len(lines) == 400
for line in lines:
    number, headword, gloss = line.split("|", 2)
    entry = words[int(number) - 1]
    assert entry["id"] == int(number) and entry["word"] == headword, line
    entry["zh"] = gloss
    prefix = "常用：" + gloss + "\n"
    if not entry["full"].startswith(prefix):
        if entry["full"].startswith("常用："):
            entry["full"] = prefix + entry["full"].split("\n", 1)[1]
        else:
            entry["full"] = prefix + entry["full"]

path.write_text(json.dumps(words, ensure_ascii=False, separators=(",", ":")))
